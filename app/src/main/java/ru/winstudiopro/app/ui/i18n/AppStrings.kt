/**
 * Нормализация отображения валюты (для обратной совместимости с записями "доллар").
 */
fun normalizeCurrencyDisplay(raw: String): String = when (raw.trim().lowercase()) {
    "доллар", "usd", "$" -> "$"
    "евро", "eur", "€" -> "€"
    "лари", "gel", "₾" -> "₾"
    "руб", "рубль", "rub", "₽" -> "₽"
    else -> raw.ifBlank { "$" }
}

